<script setup lang="ts">
import { computed, ref } from 'vue'
import AppIcon from './AppIcon.vue'
import Modal from './Modal.vue'
import type { FlowFilters } from '../types'
import { api } from '../composables/useApi'
import { activeFilterCount, directionLabel } from '../lib/format'
import { toastError, toastSuccess } from '../composables/useToasts'

const props = defineProps<{
  filters: FlowFilters
  total: number
}>()

const emit = defineEmits<{ close: [] }>()

const downloading = ref<'json' | 'har' | null>(null)
const filterCount = computed(() => activeFilterCount(props.filters))

const filterChips = computed(() => {
  const chips: string[] = []
  if (props.filters.q.trim()) chips.push(`search: ${props.filters.q.trim()}`)
  if (props.filters.host) chips.push(`host: ${props.filters.host}`)
  if (props.filters.method) chips.push(`method: ${props.filters.method}`)
  if (props.filters.status) chips.push(`status: ${props.filters.status}`)
  if (props.filters.protocol) chips.push(`protocol: ${props.filters.protocol}`)
  if (props.filters.mime.trim()) chips.push(`mime: ${props.filters.mime.trim()}`)
  if (props.filters.body_contains.trim()) chips.push(`body: ${props.filters.body_contains.trim()}`)
  if (props.filters.direction !== 'both') chips.push(directionLabel(props.filters.direction))
  return chips
})

async function download(format: 'json' | 'har'): Promise<void> {
  if (downloading.value) return
  downloading.value = format
  try {
    const filename = await api.downloadExport(format, props.filters)
    toastSuccess('Export started', filename)
  } catch (downloadError) {
    toastError(downloadError, 'Export failed')
  } finally {
    downloading.value = null
  }
}
</script>

<template>
  <Modal
    title="Export traffic"
    subtitle="Downloads use the current search filters and are generated by the backend."
    size="md"
    @close="emit('close')"
  >
    <div class="rounded-md border border-ink-700/70 bg-ink-950/25 p-3">
      <div class="flex items-center justify-between gap-2">
        <div class="flex items-center gap-1.5">
          <AppIcon name="filter" :size="11" class="text-mist-600" />
          <span class="text-[10px] font-medium text-mist-400">
            {{ filterCount ? `${filterCount} active filter${filterCount === 1 ? '' : 's'}` : 'All captured traffic' }}
          </span>
        </div>
        <span class="font-mono text-[9px] text-mist-600">{{ total.toLocaleString() }} matching</span>
      </div>
      <div v-if="filterChips.length" class="mt-2 flex flex-wrap gap-1">
        <span
          v-for="chip in filterChips"
          :key="chip"
          class="max-w-full truncate rounded border border-ink-700 bg-ink-900/60 px-1.5 py-0.5 font-mono text-[8.5px] text-mist-500"
        >{{ chip }}</span>
      </div>
      <p v-else class="mt-1.5 text-[9.5px] leading-relaxed text-mist-600">
        The export includes every flow currently in the capture store.
      </p>
    </div>

    <div class="mt-3 space-y-2">
      <button
        class="group flex w-full items-start gap-3 rounded-lg border border-ink-700 bg-ink-900/35 p-3 text-left transition hover:border-accent-500/30 hover:bg-accent-500/[0.035]"
        type="button"
        :disabled="downloading != null"
        @click="download('json')"
      >
        <div class="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border border-ink-700 bg-ink-950/50 text-accent-400/80">
          <AppIcon name="file-json" :size="17" />
        </div>
        <div class="min-w-0 flex-1">
          <div class="flex items-center gap-2">
            <span class="text-[11.5px] font-semibold text-mist-300">Native JSON</span>
            <span class="badge border-accent-500/20 bg-accent-500/[0.05] text-accent-300/80">Lossless</span>
          </div>
          <p class="mt-0.5 text-[10px] leading-relaxed text-mist-600">
            Complete flow objects, headers, bodies, and metadata. Can be
            imported back into MitmRs.
          </p>
        </div>
        <AppIcon
          :name="downloading === 'json' ? 'refresh' : 'download'"
          :size="15"
          class="mt-2 shrink-0 text-mist-600 group-hover:text-accent-300"
          :class="downloading === 'json' ? 'animate-soft-spin' : ''"
        />
      </button>

      <button
        class="group flex w-full items-start gap-3 rounded-lg border border-ink-700 bg-ink-900/35 p-3 text-left transition hover:border-accent-500/30 hover:bg-accent-500/[0.035]"
        type="button"
        :disabled="downloading != null"
        @click="download('har')"
      >
        <div class="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border border-ink-700 bg-ink-950/50 text-teal-400/80">
          <AppIcon name="globe" :size="17" />
        </div>
        <div class="min-w-0 flex-1">
          <div class="flex items-center gap-2">
            <span class="text-[11.5px] font-semibold text-mist-300">HTTP Archive (HAR)</span>
            <span class="badge border-teal-500/20 bg-teal-500/[0.05] text-teal-300/80">HAR 1.2</span>
          </div>
          <p class="mt-0.5 text-[10px] leading-relaxed text-mist-600">
            Portable format for Chrome DevTools, browser extensions, and other
            traffic analysis tools.
          </p>
        </div>
        <AppIcon
          :name="downloading === 'har' ? 'refresh' : 'download'"
          :size="15"
          class="mt-2 shrink-0 text-mist-600 group-hover:text-accent-300"
          :class="downloading === 'har' ? 'animate-soft-spin' : ''"
        />
      </button>
    </div>

    <p class="mt-3 flex items-start gap-1.5 text-[9px] leading-relaxed text-mist-700">
      <AppIcon name="shield" :size="10" class="mt-0.5 shrink-0" />
      Exports may contain credentials, cookies, and personal data. Store and
      share them accordingly.
    </p>

    <template #footer>
      <button class="btn btn-sm" type="button" :disabled="downloading != null" @click="emit('close')">
        Close
      </button>
    </template>
  </Modal>
</template>
